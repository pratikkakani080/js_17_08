// Variables

// let
    // let can be reassigned but cannot be redeclared
    let firstName = 'Pratik' // = is an assignment operator
    firstName = 'John'
    console.log(firstName);

// var
    // let can be reassigned AS WELL AS redeclared
    var a = 'five'
    var a = 'six'
    console.log(a);

// const 
    // const cannot be reassigned nor redeclared
    const c = 'one'